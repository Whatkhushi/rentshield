import crypto from 'node:crypto';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';
import { Transform, type Readable } from 'node:stream';
import { config } from '../config.js';

/**
 * File storage behind a small interface so the backend doesn't care where
 * bytes live. Today: local disk. For deployment, add a cloud driver
 * (Cloudinary / Supabase Storage / R2) that implements the same three
 * methods. No business logic changes.
 */
export interface StoredFile {
  key: string;
  sha256: string;
  size: number;
}

export interface Storage {
  /** Stream bytes in; the SHA-256 is computed in the same pass. */
  put(stream: Readable, extension: string): Promise<StoredFile>;
  get(key: string): Readable;
  remove(key: string): Promise<void>;
  /** Re-read the stored bytes and hash them (for integrity checks). */
  hash(key: string): Promise<string>;
}

class LocalDiskStorage implements Storage {
  constructor(private root: string) {}

  private pathFor(key: string) {
    // Keys are generated by us, but never trust a path blindly.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root))) throw new Error('Invalid storage key');
    return full;
  }

  async put(stream: Readable, extension: string): Promise<StoredFile> {
    const now = new Date();
    const key = `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}/${crypto.randomUUID()}${extension}`;
    const full = this.pathFor(key);
    await fsp.mkdir(path.dirname(full), { recursive: true });

    const hash = crypto.createHash('sha256');
    let size = 0;
    const hasher = new Transform({
      transform(chunk: Buffer, _enc, cb) {
        hash.update(chunk);
        size += chunk.length;
        cb(null, chunk);
      },
    });
    try {
      await pipeline(stream, hasher, fs.createWriteStream(full, { flags: 'wx' }));
    } catch (err) {
      await fsp.rm(full, { force: true });
      throw err;
    }
    return { key, sha256: hash.digest('hex'), size };
  }

  get(key: string): Readable {
    return fs.createReadStream(this.pathFor(key));
  }

  async remove(key: string) {
    await fsp.rm(this.pathFor(key), { force: true });
  }

  async hash(key: string): Promise<string> {
    const hash = crypto.createHash('sha256');
    await pipeline(this.get(key), hash);
    return hash.digest('hex');
  }
}

export const storage: Storage = new LocalDiskStorage(path.resolve(config.STORAGE_DIR));
